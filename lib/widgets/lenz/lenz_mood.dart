/// Crops of the same 1254x1254 rig (prototype `VIEWS`).
enum LenzView {
  /// Whole body. viewBox `40 -150 1180 1400`.
  full(Rect.fromLTWH(40, -150, 1180, 1400)),

  /// Head and shoulders, bottom 20% fades out. viewBox `250 -20 900 860`.
  bust(Rect.fromLTWH(250, -20, 900, 860)),

  /// Head only (avatars / circles). viewBox `300 10 720 700`.
  peek(Rect.fromLTWH(300, 10, 720, 700));

  const LenzView(this.viewBox);

  /// The visible window in the 1254x1254 artwork space.
  final Rect viewBox;

  /// Width / height of the widget (equals the viewBox aspect ratio).
  double get aspectRatio => viewBox.width / viewBox.height;

  /// `full` lets FX overflow (CSS `overflow: visible`); bust/peek clip.
  bool get clips => this != LenzView.full;

  /// `bust` fades its bottom edge (mask-image 180deg, #000 80% -> transparent).
  bool get fadesBottom => this == LenzView.bust;
}

